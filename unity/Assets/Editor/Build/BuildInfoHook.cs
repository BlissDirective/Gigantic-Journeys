using System;
using System.Diagnostics;
using System.Globalization;
using System.IO;
using UnityEditor;
using UnityEditor.Build;
using UnityEditor.Build.Reporting;
using Debug = UnityEngine.Debug;
#if UNITY_IOS
using UnityEditor.iOS.Xcode;
#endif

namespace GiganticJourneys.EditorTools.Build
{
    /// <summary>
    /// Debug-overlay build support (ticket M0-UNITY-04), debug builds only
    /// (Development, or the <c>GJ_DEBUG</c> scripting define):
    /// <list type="bullet">
    /// <item>writes the git short SHA, build number and build time into the
    /// <c>gj_build_info</c> text resource the overlay reads, under the git-ignored
    /// <c>Assets/Generated/</c>, and deletes it after the build;</item>
    /// <item>keeps the overlay's iOS share-sheet plugin (<c>GJShareSheet.mm</c>) out of
    /// release builds through <see cref="PluginImporter.SetIncludeInBuildDelegate"/>
    /// (a plugin define constraint cannot do it: plugin constraints are evaluated in
    /// the Editor, where <c>UNITY_EDITOR</c> is always defined);</item>
    /// <item>iOS: turns on <c>UIFileSharingEnabled</c> and
    /// <c>LSSupportsOpeningDocumentsInPlace</c> so saved performance reports show
    /// in the Files app (On My iPhone → Gigantic Journeys).</item>
    /// </list>
    /// Release builds get neither, matching the overlay's own exclusion.
    /// </summary>
    [InitializeOnLoad]
    public class BuildInfoHook : IPreprocessBuildWithReport, IPostprocessBuildWithReport
    {
        public const string SharePluginPath =
            "Assets/GiganticJourneys/DebugOverlay/Plugins/iOS/GJShareSheet.mm";
        public const string GeneratedFolder = "Assets/Generated";
        public const string ResourcePath = GeneratedFolder + "/Resources/gj_build_info.txt";
        public const string DebugDefine = "GJ_DEBUG";
        const string LogTag = "[GJ-BUILDINFO]";

        public int callbackOrder => 0;

        /// <summary>True between the pre- and post-process callbacks of a debug build.</summary>
        public static bool CurrentBuildIsDebug { get; set; }

        static BuildInfoHook() => RegisterPluginFilter();

        /// <summary>Include-in-build rule for the debug-only native plugin.</summary>
        public static bool IncludeDebugPlugin(string path) => CurrentBuildIsDebug;

        public static void RegisterPluginFilter()
        {
            if (AssetImporter.GetAtPath(SharePluginPath) is PluginImporter importer)
                importer.SetIncludeInBuildDelegate(IncludeDebugPlugin);
        }

        public static bool IsDebugBuild(BuildReport report)
        {
            if ((report.summary.options & BuildOptions.Development) != 0)
                return true;
            var target = NamedBuildTarget.FromBuildTargetGroup(report.summary.platformGroup);
            var defines = PlayerSettings.GetScriptingDefineSymbols(target) ?? "";
            return Array.IndexOf(defines.Split(';', ','), DebugDefine) >= 0;
        }

        /// <summary>Short commit SHA: GITHUB_SHA on CI, else <c>git rev-parse --short HEAD</c>, else "unknown".</summary>
        public static string GitShortSha()
        {
            var env = Environment.GetEnvironmentVariable("GITHUB_SHA");
            if (!string.IsNullOrEmpty(env))
                return env.Length > 7 ? env.Substring(0, 7) : env;
            try
            {
                var psi = new ProcessStartInfo("git", "rev-parse --short HEAD")
                {
                    RedirectStandardOutput = true,
                    RedirectStandardError = true,
                    UseShellExecute = false,
                    CreateNoWindow = true,
                };
                using var p = Process.Start(psi);
                if (p == null)
                    return "unknown";
                var sha = p.StandardOutput.ReadToEnd().Trim();
                p.WaitForExit(5000);
                return p.ExitCode == 0 && sha.Length > 0 ? sha : "unknown";
            }
            catch (Exception)
            {
                return "unknown";
            }
        }

        public static string BuildNumber(BuildTarget target) =>
            target == BuildTarget.iOS ? PlayerSettings.iOS.buildNumber
            : target == BuildTarget.Android
                ? PlayerSettings.Android.bundleVersionCode.ToString(CultureInfo.InvariantCulture)
            : "";

        public void OnPreprocessBuild(BuildReport report)
        {
            DeleteGenerated();
            CurrentBuildIsDebug = IsDebugBuild(report);
            RegisterPluginFilter();
            if (!CurrentBuildIsDebug)
            {
                Debug.Log($"{LogTag} release build: no build-info resource, no Documents sharing");
                return;
            }
            var sha = GitShortSha();
            var text =
                "# generated by BuildInfoHook for a debug build (M0-UNITY-04); git-ignored\n"
                + $"git_sha={sha}\n"
                + $"build_number={BuildNumber(report.summary.platform)}\n"
                + $"built_utc={DateTime.UtcNow.ToString("yyyy-MM-ddTHH:mm:ssZ", CultureInfo.InvariantCulture)}\n";
            Directory.CreateDirectory(Path.GetDirectoryName(ResourcePath));
            File.WriteAllText(ResourcePath, text);
            AssetDatabase.ImportAsset(ResourcePath, ImportAssetOptions.ForceSynchronousImport);
            Debug.Log($"{LogTag} debug build: wrote {ResourcePath} (git {sha})");
        }

        public void OnPostprocessBuild(BuildReport report)
        {
            DeleteGenerated();
            CurrentBuildIsDebug = false;
#if UNITY_IOS
            if (report.summary.platform == BuildTarget.iOS && IsDebugBuild(report))
                EnableDocumentsSharing(report.summary.outputPath);
#endif
        }

        static void DeleteGenerated()
        {
            if (AssetDatabase.IsValidFolder(GeneratedFolder))
                AssetDatabase.DeleteAsset(GeneratedFolder);
        }

#if UNITY_IOS
        static void EnableDocumentsSharing(string xcodeProject)
        {
            var plistPath = Path.Combine(xcodeProject, "Info.plist");
            if (!File.Exists(plistPath))
                return;
            var plist = new PlistDocument();
            plist.ReadFromFile(plistPath);
            plist.root.SetBoolean("UIFileSharingEnabled", true);
            plist.root.SetBoolean("LSSupportsOpeningDocumentsInPlace", true);
            plist.WriteToFile(plistPath);
            Debug.Log($"{LogTag} iOS debug build: Documents visible in the Files app");
        }
#endif
    }
}
